bool Font::init() {
    defineChars(m_glyphPixels);
    buildAtlas();

    glGenVertexArrays(1, &m_vao);
    glGenBuffers(1, &m_vbo);

    glBindVertexArray(m_vao);
    glBindBuffer(GL_ARRAY_BUFFER, m_vbo);

    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(f32), nullptr);
    glEnableVertexAttribArray(0);

    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(f32),
                          reinterpret_cast<void*>(2 * sizeof(f32)));
    glEnableVertexAttribArray(1);

    return true;
}

void Font::destroy() {
    if (m_texture) {
        glDeleteTextures(1, &m_texture);
        m_texture = 0;
    }
    if (m_vao) {
        glDeleteVertexArrays(1, &m_vao);
        m_vao = 0;
    }
    if (m_vbo) {
        glDeleteBuffers(1, &m_vbo);
        m_vbo = 0;
    }
}

void Font::buildAtlas() {
    std::memset(m_atlasData, 0, sizeof(m_atlasData));

    i32 col = 0;
    i32 row = 0;

    for (auto& [cp, pixelData] : m_glyphPixels) {
        i32 baseX = 1 + col * (FONT_W + 1);
        i32 baseY = 1 + row * (FONT_H + 1);

        for (i32 r = 0; r < FONT_H; ++r) {
            u8 byte = pixelData[r];
            for (i32 c = 0; c < FONT_W; ++c) {
                bool pixel = (byte >> (7 - c)) & 1;
                m_atlasData[baseY + r][baseX + c] = pixel ? 255 : 0;
            }
        }

        m_glyphMap[cp] = {baseX, baseY, FONT_W, FONT_H};

        ++col;
        if (col >= ATLAS_COLS) {
            col = 0;
            ++row;
        }
    }

    glGenTextures(1, &m_texture);
    glBindTexture(GL_TEXTURE_2D, m_texture);

    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, ATLAS_W, ATLAS_H, 0,
                 GL_RED, GL_UNSIGNED_BYTE, m_atlasData);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 4);

    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
}

static char32_t decodeUTF8(const std::string& text, size_t& i) {
    u8 byte = static_cast<u8>(text[i]);
    if (byte < 0x80) {
        return byte;
    } else if ((byte & 0xE0) == 0xC0) {
        if (i + 1 >= text.size()) return 0xFFFD;
        u8 b2 = static_cast<u8>(text[i + 1]);
        i += 1;
        return ((byte & 0x1F) << 6) | (b2 & 0x3F);
    } else if ((byte & 0xF0) == 0xE0) {
        if (i + 2 >= text.size()) return 0xFFFD;
        u8 b2 = static_cast<u8>(text[i + 1]);
        u8 b3 = static_cast<u8>(text[i + 2]);
        i += 2;
        return ((byte & 0x0F) << 12) | ((b2 & 0x3F) << 6) | (b3 & 0x3F);
    } else if ((byte & 0xF8) == 0xF0) {
        if (i + 3 >= text.size()) return 0xFFFD;
        u8 b2 = static_cast<u8>(text[i + 1]);
        u8 b3 = static_cast<u8>(text[i + 2]);
        u8 b4 = static_cast<u8>(text[i + 3]);
        i += 3;
        return ((byte & 0x07) << 18) | ((b2 & 0x3F) << 12) | ((b3 & 0x3F) << 6) | (b4 & 0x3F);
    }
    return 0xFFFD;
}

Font::GlyphPos Font::glyphForCodepoint(char32_t cp) const {
    auto it = m_glyphMap.find(cp);
    if (it != m_glyphMap.end()) {
        return it->second;
    }
    auto spaceIt = m_glyphMap.find(32);
    if (spaceIt != m_glyphMap.end()) {
        return spaceIt->second;
    }
    return {1, 1, FONT_W, FONT_H};
}

void Font::renderText(const std::string& text, f32 x, f32 y, f32 scale) {
    if (!m_texture || m_glyphPixels.empty()) return;

    glBindVertexArray(m_vao);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, m_texture);

    f32 atlasW = static_cast<f32>(ATLAS_W);
    f32 atlasH = static_cast<f32>(ATLAS_H);

    size_t i = 0;
    while (i < text.size()) {
        char32_t cp = decodeUTF8(text, i);
        ++i;

        GlyphPos g = glyphForCodepoint(cp);

        f32 gx = x;
        f32 gy = y;
        f32 gw = static_cast<f32>(g.w) * scale;
        f32 gh = static_cast<f32>(g.h) * scale;

        f32 tu = static_cast<f32>(g.x) / atlasW;
        f32 tv = static_cast<f32>(g.y) / atlasH;
        f32 tu2 = static_cast<f32>(g.x + g.w) / atlasW;
        f32 tv2 = static_cast<f32>(g.y + g.h) / atlasH;

        f32 verts[] = {
            gx,     gy,     tu,  tv,
            gx+gw,  gy,     tu2, tv,
            gx+gw,  gy+gh,  tu2, tv2,
            gx,     gy+gh,  tu,  tv2
        };

        glBindBuffer(GL_ARRAY_BUFFER, m_vbo);
        glBufferData(GL_ARRAY_BUFFER, sizeof(verts), verts, GL_DYNAMIC_DRAW);

        glDrawArrays(GL_TRIANGLE_FAN, 0, 4);

        x += (static_cast<f32>(FONT_W) + 1.0f) * scale;
    }
}
