static std::array<u8, 12> glyph(const char* rows[12]) {
    std::array<u8, 12> data{};
    for (i32 r = 0; r < 12; ++r) {
        u8 byte = 0;
        for (i32 c = 0; c < 8; ++c) {
            if (rows[r][c] == '#') {
                byte |= (1 << (7 - c));
            }
        }
        data[r] = byte;
    }
    return data;
}

static void defChar(std::unordered_map<char32_t, std::array<u8, 12>>& pixels,
                    char32_t cp, const char* rows[12]) {
    pixels[cp] = glyph(rows);
}

